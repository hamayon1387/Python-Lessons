# String is a data type in Python
# SLICE() FUNCTION IN PYTHON 
# A string in python can be slice for getting a part of stirngs.

name = "Hamayon"
print(name)
short_name = name[0:3] # This function start the slicing from index.start to index_end and index_end is not included.
print(short_name)

name2 = "Timor"
character1 = name2[0:1]
print(character1)

character2 = name2[2:]
print(character2)