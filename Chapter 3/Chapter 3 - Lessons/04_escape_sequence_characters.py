a = "Hamayon is a \n good good boy" # This is give me a new line in output
print(a)

b = "Hamayon is a \"developer\"" # output: Hamayon is a "developer"
print(b)

c = "Hi\t Python" # output: Hi      Python
print(c)

d = "I love \f Python"
print(d)

e = "It\'s Python" # output: It's Python
print(e)

