# DICTIONARY & SETS
# Dictionary is collection of keys-values pairs.


a = {
 "key": "value",
 "hamayon": "code",
 "marks": "100",
 "list": [1, 2, 9]
 }

print(a["key"]) # Output: "value"
print(a["list"]) # Output: [1, 2, 9]



marks = {
    "Hamayon": 100,
    "Ahamd": 90,
    "Hamid": 23
}
print(marks, type(marks))
print(marks["Hamayon"]) # The output is : 100 // We can use from keys of a dictionary to find the value of a key.


